"""Train a small NMS-free, query-based detector with a timm backbone.

This is an experiment alongside ``train_timm_detection.py`` (the existing
RetinaNet baseline).  The task head is a fixed-size set predictor inspired by
DETR-style detectors:

* a timm ``features_only`` encoder and FPN produce multi-scale image tokens;
* learned object queries attend to those tokens with standard tensor ops;
* Hungarian one-to-one matching trains each query to represent at most one
  object; and
* inference emits one box/class score per query, so deployment does not need
  anchors, class-wise NMS, or a custom post-processing operator.

The dataset is the COCO layout produced by ``dataset_builder.py``::

    dataset/
      images/{train,val,test}/...
      annotations/instances_{train,val,test}.json

Images are stretched to a fixed square by default.  This matches the embedded
BW8/C24 preprocessing generated by the companion exporter.
"""

