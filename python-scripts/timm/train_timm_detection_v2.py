def main() -> None:
    args = parse_args()
    if args.imgsz < 32 or args.imgsz % 32:
        raise ValueError("--imgsz must be at least 32 and divisible by 32")
    if args.batch < 1 or args.epochs < 1 or args.patience < 0 or args.min_epochs < 0:
        raise ValueError("--batch/--epochs must be positive and --patience/--min-epochs cannot be negative")
    if args.fpn_channels < 8 or (args.num_queries is not None and args.num_queries < 1) \
            or args.decoder_layers < 1 or args.attention_heads < 1:
        raise ValueError("head dimensions must be positive")
    if not 0 <= args.score_threshold <= 1:
        raise ValueError("--score-threshold must be between 0 and 1")
    if args.fpn_channels % args.attention_heads:
        raise ValueError("--fpn-channels must be divisible by --attention-heads")

    set_seed(args.seed, args.deterministic)
    device = resolve_device(args.device)
    workers = args.workers
    if workers == -1:
        workers = min(8, max(1, (os.cpu_count() or 1) // 2)) if device.type == "cuda" else 0
    amp_enabled = bool(args.amp and device.type == "cuda")
    amp_dtype = torch.float16 if args.amp_dtype == "float16" else torch.bfloat16
    pin_memory = device.type == "cuda"

    data = args.data.expanduser().resolve()
    output = args.output.expanduser().resolve()
    train_set = CocoDetectionDataset(data, "train", args.imgsz, True, args.stretch_to_input_size, args.max_train_images)
    val_set = CocoDetectionDataset(data, "val", args.imgsz, False, args.stretch_to_input_size, args.max_val_images)
    if train_set.class_names != val_set.class_names:
        raise ValueError(f"Train/val categories differ: {train_set.class_names} != {val_set.class_names}")
    test_set = None
    if args.run_test and (data / "annotations" / "instances_test.json").is_file():
        test_set = CocoDetectionDataset(data, "test", args.imgsz, False, args.stretch_to_input_size, args.max_test_images)
        if train_set.class_names != test_set.class_names:
            raise ValueError(f"Train/test categories differ: {train_set.class_names} != {test_set.class_names}")

    split_maxima = {
        "train": train_set.max_labeled_boxes_per_image(),
        "val": val_set.max_labeled_boxes_per_image(),
    }
    if test_set is not None:
        split_maxima["test"] = test_set.max_labeled_boxes_per_image()
    max_labeled_boxes = max(split_maxima.values(), default=0)
    requested_num_queries = args.num_queries
    if requested_num_queries is None:
        args.num_queries = auto_num_queries(max_labeled_boxes)
        query_selection = "auto"
    else:
        if requested_num_queries < max_labeled_boxes:
            raise ValueError(
                f"--num-queries={requested_num_queries} is smaller than the largest loaded target set "
                f"({max_labeled_boxes} boxes); increase it or omit the flag for automatic sizing"
            )
        query_selection = "explicit"
    print(
        f"query_capacity={args.num_queries}; query_selection={query_selection}; "
        f"max_labeled_boxes={max_labeled_boxes}; split_maxima={split_maxima}"
    )

    model, backbone, data_config = build_detector(
        args.model,
        len(train_set.class_names),
        args.fpn_channels,
        args.num_queries,
        args.decoder_layers,
        args.attention_heads,
        pretrained=args.pretrained,
        bbox_loss_weight=args.bbox_loss_weight,
        giou_loss_weight=args.giou_loss_weight,
        no_object_weight=args.no_object_weight,
    )
    data_config = dict(data_config)
    data_config.update({
        "input_size": [3, args.imgsz, args.imgsz],
        "interpolation": "bilinear",
        "resize_mode": "stretch_to_input_size" if args.stretch_to_input_size else "native",
        "stretch_to_input_size": bool(args.stretch_to_input_size),
    })
    model.to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)
    scaler = torch.amp.GradScaler("cuda", enabled=amp_enabled)
    train_loader = make_loader(train_set, args.batch, workers, pin_memory, args.seed, True)
    val_loader = make_loader(val_set, args.batch, workers, pin_memory, args.seed + 1, False)

    model_config = {
        "architecture": "nms_free_query",
        "nms_required": False,
        "model_name": args.model,
        "out_indices": list(OUT_INDICES),
        "fpn_channels": args.fpn_channels,
        "num_queries": args.num_queries,
        "num_queries_selection": query_selection,
        "max_labeled_boxes": max_labeled_boxes,
        "auto_query_headroom": DEFAULT_AUTO_QUERY_HEADROOM,
        "auto_query_round_to": DEFAULT_AUTO_QUERY_ROUND_TO,
        "decoder_layers": args.decoder_layers,
        "attention_heads": args.attention_heads,
        "bbox_loss_weight": args.bbox_loss_weight,
        "giou_loss_weight": args.giou_loss_weight,
        "no_object_weight": args.no_object_weight,
        "imgsz": args.imgsz,
        "stretch_to_input_size": args.stretch_to_input_size,
        "feature_channels": backbone.feature_channels,
        "feature_reductions": backbone.feature_reductions,
    }
    parameters = {
        "epochs": args.epochs,
        "batch": args.batch,
        "lr": args.lr,
        "weight_decay": args.weight_decay,
        "workers": workers,
        "amp": amp_enabled,
        "amp_dtype": args.amp_dtype if amp_enabled else None,
        "device": str(device),
        "seed": args.seed,
        "deterministic": args.deterministic,
        "pretrained": args.pretrained,
        "num_queries_requested": requested_num_queries,
        "score_threshold": args.score_threshold,
        "max_train_images": args.max_train_images,
        "max_val_images": args.max_val_images,
        "max_test_images": args.max_test_images,
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "config.json").write_text(
        json.dumps({"model_config": model_config, "data_config": data_config, "parameters": parameters}, indent=2),
        encoding="utf-8",
    )

    best_score = -1.0
    epochs_without_improvement = 0
    history: list[dict[str, Any]] = []
    print(
        f"training nms_free_query; backbone={args.model}; classes={train_set.class_names}; "
        f"images={len(train_set)}/{len(val_set)}; queries={args.num_queries}; device={device}; imgsz={args.imgsz}; "
        "nms_required=false"
    )
    for epoch in range(1, args.epochs + 1):
        if device.type == "cuda":
            torch.cuda.reset_peak_memory_stats(device)
        print("\n      Epoch    GPU_mem   box_loss   cls_loss  giou_loss  Instances       Size")
        train_progress = make_progress(len(train_loader), f"{epoch:7d}/{args.epochs:<3d}")
        try:
            train_losses = train_epoch(
                model,
                train_loader,
                optimizer,
                scaler,
                device,
                amp_enabled,
                amp_dtype,
                progress=train_progress,
                epoch=epoch,
                total_epochs=args.epochs,
                imgsz=args.imgsz,
            )
        finally:
            train_progress.close()

        validation_description = (
            "                 Class     Images  Instances      Box(P          R      mAP50  mAP50-95"
        )
        val_progress = make_progress(len(val_loader), validation_description)
        try:
            metrics = evaluate(
                model,
                val_loader,
                train_set.class_names,
                device,
                args.score_threshold,
                progress=val_progress,
            )
        finally:
            val_progress.close()
        print_validation_summary(metrics, len(val_set))
        scheduler.step()
        row = {"epoch": epoch, **train_losses, **metrics, "lr": optimizer.param_groups[0]["lr"]}
        history.append(row)
        print(
            f"epoch={epoch:03d} loss={train_losses['loss_total']:.5f} "
            f"class={train_losses['loss_class']:.5f} bbox={train_losses['loss_bbox']:.5f} "
            f"giou={train_losses['loss_giou']:.5f} map50={metrics['map50']:.5f} "
            f"map50_95={metrics['map50_95']:.5f} precision50={metrics['precision50']:.5f} "
            f"recall50={metrics['recall50']:.5f}"
        )
        score = float(metrics["map50"])
        if score > best_score + 1e-8:
            best_score = score
            epochs_without_improvement = 0
            save_checkpoint(output / "best.pt", model, optimizer, epoch, train_set.class_names, args.model, data_config, model_config, metrics)
        else:
            epochs_without_improvement += 1
        save_checkpoint(output / "last.pt", model, optimizer, epoch, train_set.class_names, args.model, data_config, model_config, metrics)
        if args.patience and epoch >= args.min_epochs and epochs_without_improvement >= args.patience:
            print(f"early_stop=patience({args.patience})")
            break

    with (output / "history.csv").open("w", newline="", encoding="utf-8") as handle:
        if history:
            fieldnames = sorted({key for row in history for key in row if not isinstance(row[key], dict)})
            writer = csv.DictWriter(handle, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows({key: value for key, value in row.items() if key in fieldnames} for row in history)

    best = torch.load(output / "best.pt", map_location=device, weights_only=False)
    model.load_state_dict(best["model_state_dict"])
    best_metrics = evaluate(model, val_loader, train_set.class_names, device, args.score_threshold)
    print(
        f"best_epoch={best['epoch']} best_map50={best_metrics['map50']:.5f} "
        f"best_map50_95={best_metrics['map50_95']:.5f}"
    )
    if test_set is not None:
        test_loader = make_loader(test_set, args.batch, 0, pin_memory, args.seed + 2, False)
        test_metrics = evaluate(model, test_loader, train_set.class_names, device, args.score_threshold)
        print(
            f"test_map50={test_metrics['map50']:.5f} test_precision50={test_metrics['precision50']:.5f} "
            f"test_recall50={test_metrics['recall50']:.5f} test_map50_95={test_metrics['map50_95']:.5f}"
        )
        (output / "test_metrics.json").write_text(json.dumps(test_metrics, indent=2), encoding="utf-8")

    metadata = {
        "task": "object_detection",
        "architecture": "nms_free_query",
        "nms_required": False,
        "model_name": args.model,
        "classes": train_set.class_names,
        "model_config": model_config,
        "data_config": data_config,
        "training_result": {"best_epoch": int(best["epoch"]), "best_val_metrics": best_metrics},
    }
    (output / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
